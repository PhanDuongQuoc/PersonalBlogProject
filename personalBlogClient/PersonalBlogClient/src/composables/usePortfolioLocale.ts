export const usePortfolioLocale = () => {
  const text = computed(() => messages[locale.value]);

  const setLocale = (value: PortfolioLocale) => {
    locale.value = value;
    window.localStorage.setItem('portfolio-locale', value);
  };

  return { locale, setLocale, text };
};
